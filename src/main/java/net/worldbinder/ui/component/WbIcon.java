    public static final int SIZE = 7;
    private final int[] rects;

    WbIcon(String... rows) {
        List<Integer> runs = new ArrayList<>();
        for (int row = 0; row < rows.length; row++) {
            String pixels = rows[row];
            for (int column = 0; column < pixels.length(); ) {
                if (pixels.charAt(column) != '1') {
                    column++;
                    continue;
                }
                int start = column;
                while (column < pixels.length() && pixels.charAt(column) == '1') column++;
                runs.add(start);
                runs.add(row);
                runs.add(column - start);
            }
        }
        rects = runs.stream().mapToInt(Integer::intValue).toArray();
    }

    public void draw(GuiGraphicsExtractor context, int x, int y, int scale, int color) {
        int s = Math.max(1, scale);
        for (int i = 0; i < rects.length; i += 3) {
            int px = x + rects[i] * s;
            int py = y + rects[i + 1] * s;
            context.fill(px, py, px + rects[i + 2] * s, py + s, color);
        }
    }

    /** Draws the icon with a one pixel drop shadow for legibility on busy backgrounds. */
    public void drawShadowed(GuiGraphicsExtractor context, int x, int y, int scale, int color) {
        draw(context, x + 1, y + 1, scale, WbTheme.alpha(0xAA000000, (color >>> 24) / 255.0F));
        draw(context, x, y, scale, color);
    }

    public static WbIcon movement(net.worldbinder.movement.MovementTool tool) {
        try {
            return valueOf(tool.name());
        } catch (IllegalArgumentException ignored) {
            return MOVEMENT;
        }
    }
